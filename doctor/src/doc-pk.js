/* ---------- Разбор ---------- */
const PK_LIST = s => String(s || '').split(/;\s*/).map(x => x.trim()).filter(Boolean);
const PK_KEY = s => s.replace(/\s*\(.*$/, '').trim();
const PK_MINOR = s => /минорно|слабо|in vitro|вероятно/.test(s);
// пути метаболизма, по которым считается нагрузка
const ENZ = [
  ['CYP3A4', /CYP3A4/], ['CYP2D6', /CYP2D6/], ['CYP1A2', /CYP1A2/], ['CYP2C9', /CYP2C9/], ['CYP2C19', /CYP2C19/], ['CYP2C8', /CYP2C8/],
  ['CYP2E1', /CYP2E1/], ['CYP2A6', /CYP2A6/], ['CYP4F2', /CYP4F2/], ['UGT', /\bUGT/], ['SULT', /\bSULT/], ['COMT', /\bCOMT/], ['MAO', /\bMAO/],
  ['AADC', /\bAADC/], ['GST', /\bGST\b/], ['P-gp', /P-gp/], ['OATP', /OATP/],
  ['Метилирование', /NNMT|BHMT|метилтрансфераз|S-метилир|метионинсинтаз|деметилир/],
  ['Почки', /почки/]
];
const ENZ_N = { 'Метилирование': 'Метилирование (SAMe, NNMT, BHMT)', 'Почки': 'Почки (выведение)', 'UGT': 'UGT (глюкуронидация)', 'SULT': 'SULT (сульфатирование)', 'COMT': 'COMT', 'MAO': 'MAO', 'AADC': 'AADC (декарбоксилаза)', 'GST': 'GST (глутатион-конъюгация)', 'P-gp': 'P-гликопротеин', 'OATP': 'OATP (транспорт)' };
const TAG_INH = { cyp3a4inh: 'CYP3A4', cyp3a4inh_mild: 'CYP3A4 (слабо)', cyp2d6inh: 'CYP2D6', pgpinh: 'P-gp' };
const TAG_IND = { cyp1a2ind: 'CYP1A2' };
function pkOf(id) {
  const p = PK[id]; if (!p) return null;
  const m = BY[id];
  const inh = PK_LIST(p[3]), ind = PK_LIST(p[4]);
  for (const t in TAG_INH) if (m.T.has(t) && !inh.some(x => PK_KEY(x) === PK_KEY(TAG_INH[t]))) inh.push(TAG_INH[t]);
  for (const t in TAG_IND) if (m.T.has(t) && !ind.some(x => PK_KEY(x) === TAG_IND[t])) ind.push(TAG_IND[t]);
  return { rec: PK_LIST(p[0]), enz: PK_LIST(p[1]), met: PK_LIST(p[2]), inh, ind };
}
function enzKeys(list) {
  const out = [];
  list.forEach(s => ENZ.forEach(([k, re]) => { if (re.test(s) && !out.some(o => o.k === k)) out.push({ k, minor: PK_MINOR(s) }); }));
  return out;
}

/* ---------- Нагрузка состава ---------- */
function pkLoad(ids, doseMg) {
  const by = {};
  const get = k => (by[k] = by[k] || { k, n: ENZ_N[k] || k, sub: [], inh: [], ind: [] });
  ids.forEach(id => {
    const p = pkOf(id); if (!p) return;
    enzKeys(p.met).forEach(e => get(e.k).sub.push({ id, minor: e.minor }));
    enzKeys(p.inh).forEach(e => get(e.k).inh.push({ id, minor: e.minor }));
    enzKeys(p.ind).forEach(e => get(e.k).ind.push({ id, minor: e.minor }));
  });
  const rows = Object.values(by).map(r => {
    const w = r.sub.reduce((a, s) => a + (s.minor ? 0.5 : 1), 0);
    const inhW = r.inh.filter(x => r.sub.some(s => s.id !== x.id)).reduce((a, s) => a + (s.minor ? 0.5 : 1), 0);
    let lvl = w >= 3 ? 3 : w >= 2 ? 2 : r.sub.length ? 1 : 0;
    if (r.sub.length && inhW >= 1) lvl = Math.min(3, lvl + 1);
    else if (r.sub.length && inhW > 0) lvl = Math.max(lvl, 2);
    // высокоёмкие пути: нагрузка не выше умеренной (почки — значимо при ХБП)
    if (['UGT', 'SULT', 'Почки', 'GST'].includes(r.k)) lvl = Math.min(lvl, 2);
    const note = [];
    if (r.inh.some(x => r.sub.some(s => s.id !== x.id))) note.push('ингибитор в составе — концентрация субстратов может расти');
    if (r.ind.some(x => r.sub.some(s => s.id !== x.id))) note.push('индуктор в составе — эффект субстратов может ослабевать');
    if (r.sub.length >= 2) note.push('конкуренция субстратов за фермент');
    return Object.assign(r, { w, lvl, note });
  }).filter(r => r.sub.length || r.inh.length || r.ind.length);
  rows.sort((a, b) => b.lvl - a.lvl || b.sub.length - a.sub.length || b.inh.length - a.inh.length);
  // общие мишени
  const tgt = {};
  ids.forEach(id => { const p = pkOf(id); if (!p) return; p.rec.concat(p.enz).forEach(s => { const k = PK_KEY(s); if (!k) return; (tgt[k] = tgt[k] || new Set()).add(id); }); });
  const shared = Object.entries(tgt).filter(([, s]) => s.size >= 2).map(([k, s]) => ({ k, ids: [...s] })).sort((a, b) => b.ids.length - a.ids.length);
  return { rows, shared };
}
